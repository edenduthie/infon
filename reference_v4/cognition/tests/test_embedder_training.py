"""Verify that the multi-task embedder trains on a synthetic mini-corpus.

Four assertions:
    1. Total loss decreases monotonically in expectation.
    2. Anchor multi-label accuracy > 70%.
    3. Evidentiality classification accuracy > 70%.
    4. Same-template sentences cluster closer than different-template.
"""
